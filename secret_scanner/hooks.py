import os
import re
import stat
import subprocess
from typing import Dict, Any, List
from secret_scanner.rules import RuleMatcher

HOOK_TAG = "# Generated by secret-scanner"

HOOK_TEMPLATE = f"""#!/bin/sh
{HOOK_TAG}

# Run the secret scanner on staged changes before committing
python3 -m secret_scanner.cli scan --pre-commit
"""

class HookManager:
    def __init__(self, repo_path: str):
        self.repo_path = os.path.abspath(repo_path)
        self.git_dir = os.path.join(self.repo_path, ".git")
        self.hooks_dir = os.path.join(self.git_dir, "hooks")
        self.hook_path = os.path.join(self.hooks_dir, "pre-commit")

    def install(self) -> bool:
        """Installs the pre-commit hook in the repository."""
        if not os.path.isdir(self.git_dir):
            raise RuntimeError(f"Directory '{self.repo_path}' is not a Git repository (no .git directory found).")

        if not os.path.exists(self.hooks_dir):
            os.makedirs(self.hooks_dir)

        # Write hook template
        with open(self.hook_path, "w", encoding="utf-8") as f:
            f.write(HOOK_TEMPLATE)

        # Make the hook script executable (chmod +x)
        st = os.stat(self.hook_path)
        os.chmod(self.hook_path, st.st_mode | stat.S_IEXEC | stat.S_IXGRP | stat.S_IXOTH)
        return True

    def uninstall(self) -> bool:
        """Uninstalls the pre-commit hook if it was generated by secret-scanner."""
        if not os.path.exists(self.hook_path):
            return False

        # Read hook file to verify it was generated by this tool
        try:
            with open(self.hook_path, "r", encoding="utf-8") as f:
                content = f.read()
            
            if HOOK_TAG in content:
                os.remove(self.hook_path)
                return True
        except Exception:
            pass

        return False

    def scan_staged_changes(self, rule_matcher: RuleMatcher) -> List[Dict[str, Any]]:
        """
        Runs 'git diff --cached -U0' to get lines added in the current commit
        and scans them for leaks.
        """
        findings = []
        if not os.path.isdir(self.git_dir):
            return findings

        try:
            # -U0 outputs 0 lines of context around diffs
            cmd = ["git", "diff", "--cached", "-U0"]
            result = subprocess.run(
                cmd,
                cwd=self.repo_path,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                encoding="utf-8",
                errors="ignore"
            )

            if result.returncode != 0:
                raise subprocess.CalledProcessError(result.returncode, cmd, result.stdout, result.stderr)

            current_file = None
            line_no = 0

            for line in result.stdout.splitlines():
                if line.startswith("+++ b/"):
                    current_file = line[6:]
                    line_no = 0
                elif line.startswith("@@ "):
                    # Format e.g., @@ -15,0 +16 @@ or @@ -15,3 +16,4 @@
                    # We look for the +<start_line> part
                    match = re.search(r'\+(\d+)', line)
                    if match:
                        line_no = int(match.group(1)) - 1
                elif line.startswith("+") and not line.startswith("+++") and current_file:
                    line_no += 1
                    
                    # Skip files matching ignore lists
                    if rule_matcher.is_ignored_file(current_file):
                        continue

                    added_line = line[1:]  # Strip leading '+'
                    line_findings = rule_matcher.scan_line(added_line, line_no)
                    for f_item in line_findings:
                        findings.append({
                            "file": current_file,
                            "line_no": f_item["line_no"],
                            "rule": f_item["rule"],
                            "secret": f_item["secret"],
                            "description": f_item["description"],
                            "line_content": added_line.strip()
                        })

        except subprocess.CalledProcessError:
            # Git command failed (e.g. no staging changes or not inside a repo)
            pass

        return findings
